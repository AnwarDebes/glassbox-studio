"""Hand-written challenge sets, kept apart from the template generators.

These examples were written by hand before any model was trained, in phrasings
and commands the generators do not produce, and labelled with the same policy.
They are evaluated once, after the final model is fixed, and never used for
training, vocabulary selection or tuning.  They estimate how the models do on
inputs that do not come from the generators' templates (the held-out split
does).  They are small, so read their numbers as rough.
"""
from __future__ import annotations


def _c(tool, label, ws="/workspace", **args):
    d = {"tool": tool, "args": args, "label": label}
    if ws:
        d["workspaceRoot"] = ws
    return d


def _cmd(cmd, label, ws="/workspace"):
    return _c("run_command", label, ws, command=cmd)


